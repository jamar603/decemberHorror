export const LANGS = { fr: { label: 'Français', dict: fr as Record<Key, string> }, en: { label: 'English', dict: en } };
export type Lang = keyof typeof LANGS;

let dict: Record<Key, string> = fr;
export let lang: Lang = 'fr';
export function setLang(l: Lang) {
  lang = LANGS[l] ? l : 'fr';
  dict = LANGS[lang].dict;
  document.documentElement.lang = lang;
}

export function t(k: Key, vars?: Record<string, string | number>) {
  let s = dict[k] ?? fr[k] ?? k;
  if (vars) for (const [n, v] of Object.entries(vars)) s = s.replaceAll(`{${n}}`, String(v));
  return s;
}
